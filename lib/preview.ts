import "server-only";
import { createHmac, timingSafeEqual } from "node:crypto";

/**
 * Draft preview for TTR OS's page fixer, which reads a page's unpublished
 * Sanity changes before publishing them. Same contract as TTR's other v2
 * sites (TTR OS lib/connectors/sanity.ts, previewUrl):
 *
 *   /api/preview?path=<site path>&exp=<unix seconds>&sig=<hex>
 *   sig = HMAC-SHA256(PREVIEW_SECRET, "<path>\n<exp>")
 *
 * A link is good until exp, which is at most 30 days away. The path must be
 * on this site (starts with one "/"), so a link can never redirect elsewhere.
 * PREVIEW_SECRET is generated by TTR OS's bootstrap and set in Vercel; with
 * no secret, preview is off.
 */
export const NOT_SET_UP = "Preview is not set up";
const MAX_DAYS = 30;
/** Preview responses are never cached or indexed. */
export const PREVIEW_HEADERS: Record<string, string> = { "Cache-Control": "no-store", "X-Robots-Tag": "noindex, nofollow" };

export type PreviewLink = { path?: string | null; exp?: string | null; sig?: string | null };
export type PreviewCheck = { ok: true; path: string } | { ok: false; why: string };

export function previewSecret(): string {
  return process.env.PREVIEW_SECRET || process.env.SANITY_PREVIEW_SECRET || "";
}

export function signPreview(secret: string, path: string, exp: number | string): string {
  return createHmac("sha256", secret).update(`${path}\n${exp}`).digest("hex");
}

export function checkPreviewLink(link: PreviewLink, secret: string, now = Date.now()): PreviewCheck {
  if (!secret) return { ok: false, why: NOT_SET_UP };
  const path = link.path || "";
  const exp = link.exp || "";
  const sig = (link.sig || "").toLowerCase();
  if (!path.startsWith("/") || path.startsWith("//") || path.includes("\\") || /[\r\n]/.test(path)) return { ok: false, why: "Invalid path" };
  if (!/^\d{1,12}$/.test(exp)) return { ok: false, why: "Invalid expiry" };
  const expSec = Number(exp);
  const nowSec = Math.floor(now / 1000);
  if (expSec < nowSec) return { ok: false, why: "Link expired" };
  if (expSec > nowSec + (MAX_DAYS + 1) * 86_400) return { ok: false, why: "Invalid expiry" };
  if (!/^[0-9a-f]{64}$/.test(sig)) return { ok: false, why: "Invalid signature" };
  const want = Buffer.from(signPreview(secret, path, exp), "hex");
  if (!timingSafeEqual(want, Buffer.from(sig, "hex"))) return { ok: false, why: "Invalid signature" };
  return { ok: true, path };
}
